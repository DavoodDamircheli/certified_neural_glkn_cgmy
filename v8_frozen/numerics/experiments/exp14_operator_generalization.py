"""exp14 -- Task 14 (working prompt): make it an operator, not a
parameter map.

Diagnosis (confirmed in notes/14_operator_not_parameter_map.md): every
existing checkpoint in this project (including `checkpoints/
deeponet_final.pt`, `FINAL_MODEL_NAME`) was trained with `strike` fixed
at 100.0 for every single query -- the DeepONet branch net's `psi` input
never varied, so the learned map is provably `mu -> u(mu)`, not
`(psi, mu) -> u(psi, mu)`. This script implements the task's "minimum"
bullet: vary `K` over `[70, 150]` (see `configs/base.yaml`'s
`operator_generalization` block for the validated range and why it's
safe on the existing FIXED mesh), train a NEW DeepONet on data where
`psi` genuinely varies, and report operator generalization across three
held-out tiers, compared directly against the OLD (K=100-only)
checkpoint evaluated on the SAME queries.

Does NOT touch `checkpoints/deeponet_final.pt` or `data/
production_dataset.h5` -- the new model is trained fresh, in memory, on a
NEW dataset (`data/operator_dataset.h5`, generated by this script), the
same "never overwrite the canonical checkpoint" convention
`exp12_seed_variance.py` already established. Does NOT touch
`data/sampling.py`'s `ParameterBox`/`strike` (the frozen, single-scalar
convention every other experiment relies on) -- strike-varying sampling
lives entirely in the new, separate `data.operator_sampling` module.

Three held-out generalization tiers (put-only scope: "payoff parameters"
for a plain European put reduces to strike alone, so the task's "unseen
mu with known family" / "unseen strike" / "unseen payoff parameters" /
"unseen combinations" four-way list collapses to three genuinely
distinct regimes here -- stated explicitly rather than forcing a fourth
that doesn't exist for this payoff family):

  1. unseen_mu: fresh (mu, K) jointly Sobol-sampled from the SAME
     training-style distribution (full mu box, K excluding the held-out
     gap) -- ordinary interpolation-style generalization.
  2. unseen_strike: fresh mu, K drawn ONLY from the held-out gap
     `[95, 105]` (configs/base.yaml) -- NEVER seen during training, the
     genuine "unseen strike" test. Includes K=100 itself, so the exact
     query the OLD checkpoint was exclusively trained on is directly
     comparable here.
  3. unseen_combo: deliberately correlated, edge-biased (mu, K) pairs
     (`data.operator_sampling.sample_operator_combo`) -- a joint
     combination style a uniform-over-the-box training set
     under-represents.

For each tier, both the NEW operator model and the OLD (K=100-only)
parameter-map model are evaluated on the IDENTICAL queries, reporting
relative L2, relative energy error, the guaranteed certificate
(eta_guar), and effectivity (eta_guar / E_i) -- the task's literal metric
list, via this project's own established certification machinery
(exp_common.compute_certificates), never a new certificate formula.

Outputs: data/operator_dataset.h5 (new training data), results/
exp14_operator_generalization.h5, figures/exp14_operator_generalization.png,
tables/exp14_operator_generalization.tex.
"""

from __future__ import annotations

import time
import warnings

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import torch

from cgmy.operators import OperatorCache
from data import payoff_family
from data.dataset import generate_one_sample, write_sample
from data.sampling import load_parameter_box
from data.operator_sampling import (
    load_operator_range,
    operator_box_from,
    sample_operator_combo,
    sample_operator_gap,
    sample_operator_sobol,
)
from exp_common import (
    CHECKPOINTS_DIR,
    CONFIG_PATH,
    FIGURES_DIR,
    FIXED_MESH,
    FIXED_MESH_INFO,
    REPO_ROOT,
    RESULTS_DIR,
    TABLES_DIR,
    TIME_GRID,
    compute_certificates,
    fmt,
    get_ops,
    relative_energy_error,
    relative_l2_error,
    true_error_Ei,
    write_h5,
    write_latex_table,
)
from cgmy.dirichlet_bc import project_bc
from learning.deeponet_coeff import DeepONetCoeffNet
from learning.losses import mass_weighted_loss
from learning.normalization import normalize_mu, normalize_psi, normalize_tau, stats_from_box

torch.set_default_dtype(torch.float64)

DATASET_PATH = REPO_ROOT / "data" / "operator_dataset.h5"
N_TRAIN = 400
N_EPOCHS = 3000
LR = 2e-3
SEED = 0
TRAIN_SEED = 150150

N_TEST_PER_TIER = 30
TIER_SEEDS = {"unseen_mu": 150200, "unseen_strike": 150300, "unseen_combo": 150400}

DEEPONET_KWARGS = {"mu_dim": 6, "latent_dim": 64, "branch_hidden": (128, 128), "trunk_hidden": (64, 64)}


def build_tensors(trajs, ops, stats):
    tau_l, tau_norm_l, mu_tilde_l, psi_l, c0_l, target_l = [], [], [], [], [], []
    for mu, payoff, traj in trajs:
        mu_tilde = normalize_mu(mu, stats)
        psi = normalize_psi(payoff_family.european_put(payoff.strike, ops), payoff.strike)
        for n, tau in enumerate(traj.time_grid):
            tau_l.append([tau]); tau_norm_l.append([normalize_tau(tau, mu.T)])
            mu_tilde_l.append(mu_tilde); psi_l.append(psi)
            c0_l.append(traj.initial_coefficients); target_l.append(traj.coefficients[n])
    return {
        "tau": torch.tensor(np.array(tau_l)), "tau_norm": torch.tensor(np.array(tau_norm_l)),
        "mu_tilde": torch.tensor(np.array(mu_tilde_l)), "psi": torch.tensor(np.array(psi_l)),
        "c0": torch.tensor(np.array(c0_l)), "target": torch.tensor(np.array(target_l)),
    }


def train_deeponet(tensors, mass_matrix_dense, n_dof, seed, n_epochs, lr):
    kwargs = dict(DEEPONET_KWARGS, psi_dim=n_dof)
    torch.manual_seed(seed)
    net = DeepONetCoeffNet(**kwargs)
    optimizer = torch.optim.Adam(net.parameters(), lr=lr)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=n_epochs, eta_min=lr * 1e-3)
    t0 = time.time()
    for _ in range(n_epochs):
        optimizer.zero_grad()
        pred = net(tensors["tau"], tensors["tau_norm"], tensors["mu_tilde"], tensors["psi"], tensors["c0"])
        loss = mass_weighted_loss(pred, tensors["target"], mass_matrix_dense)
        loss.backward()
        optimizer.step()
        scheduler.step()
    net.eval()
    return net, time.time() - t0, float(loss.item())


def load_old_checkpoint(n_dof: int) -> torch.nn.Module:
    """Load checkpoints/deeponet_final.pt's raw weights directly (NOT via
    exp_common.load_models's full box-compatibility check -- that check
    would correctly flag this checkpoint's single-strike training box as
    incompatible with the operator-generalization box, which is expected
    and exactly the point of this comparison, not an error to guard
    against)."""
    payload = torch.load(CHECKPOINTS_DIR / "deeponet_final.pt", weights_only=False)
    net = DeepONetCoeffNet(**payload["model_init_kwargs"])
    net.load_state_dict(payload["model_state_dict"])
    net.eval()
    return net


def predict_raw(model, mu, payoff, ops: OperatorCache, stats, c0: np.ndarray, time_grid: np.ndarray) -> np.ndarray:
    """Same convention as exp_common.predict, but builds psi from THIS
    query's own payoff.strike (exp_common.predict always uses the
    module-level fixed STRIKE=100.0 payoff, which is exactly the
    constant-psi problem this task fixes -- not reusable here)."""
    mu_tilde = normalize_mu(mu, stats)
    psi = payoff_family.european_put(payoff.strike, ops)
    raw = model.predict_trajectory(mu_tilde, psi, c0, time_grid, mu.T)
    return project_bc(raw, mu, payoff, FIXED_MESH_INFO, time_grid)


def evaluate_model(model, test_trajs, ops, stats) -> dict[str, list[float]]:
    rel_l2, rel_energy, eta_guar_l, effectivity_l = [], [], [], []
    n_not_spd = 0
    for mu, payoff, traj in test_trajs:
        c0 = traj.initial_coefficients
        pred = predict_raw(model, mu, payoff, ops, stats, c0, traj.time_grid)
        rel_l2.append(relative_l2_error(pred, traj.coefficients, ops))
        rel_energy.append(relative_energy_error(pred, traj.coefficients, mu, ops))
        cert = compute_certificates(traj, pred, mu, ops)
        if cert.is_spd:
            E_i = true_error_Ei(pred, traj.coefficients, ops)
            eta_guar_l.append(cert.eta_guar)
            if E_i > 0:
                effectivity_l.append(cert.eta_guar / E_i)
        else:
            n_not_spd += 1
    return {"rel_l2": rel_l2, "rel_energy": rel_energy, "eta_guar": eta_guar_l,
            "effectivity": effectivity_l, "n_not_spd": n_not_spd, "n": len(test_trajs)}


def main() -> None:
    ops = get_ops()
    box = load_parameter_box(CONFIG_PATH)
    stats = stats_from_box(box)
    strike_min, strike_max, strike_holdout = load_operator_range(CONFIG_PATH)
    obox = operator_box_from(box, strike_min, strike_max)
    n_dof = ops.n_dof

    # ── Generate the new, strike-varying training dataset ──────────────
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        train_samples = sample_operator_sobol(obox, N_TRAIN, seed=TRAIN_SEED, exclude_strike_range=strike_holdout)

    print(f"exp14: solving {N_TRAIN} strike-varying training trajectories "
          f"(K in [{strike_min}, {strike_max}] \\ {strike_holdout})...")
    t0 = time.time()
    train_trajs = []
    n_failed = 0
    for i, (mu, payoff) in enumerate(train_samples):
        result = generate_one_sample(mu, payoff, FIXED_MESH, TIME_GRID, mode="toeplitz")
        write_sample(DATASET_PATH, i, "train", result)
        if result.ok:
            train_trajs.append((mu, payoff, result.traj))
        else:
            n_failed += 1
        if (i + 1) % 100 == 0:
            print(f"  {i + 1}/{N_TRAIN}  ({n_failed} failed so far)")
    print(f"...done in {time.time() - t0:.1f}s -- {len(train_trajs)}/{N_TRAIN} solved successfully "
          f"({n_failed} failed)")

    # ── Train the operator model ────────────────────────────────────────
    mass_matrix_dense = torch.tensor(np.array([ops.apply_M(e) for e in np.eye(n_dof)]).T)
    tensors = build_tensors(train_trajs, ops, stats)
    print(f"\nexp14: training the operator DeepONet ({N_EPOCHS} epochs, "
          f"n_train={len(train_trajs)})...")
    operator_net, t_train, final_loss = train_deeponet(tensors, mass_matrix_dense, n_dof, SEED, N_EPOCHS, LR)
    print(f"  ...done in {t_train:.1f}s, final train loss={final_loss:.4e}")

    old_net = load_old_checkpoint(n_dof)

    # ── Build the three held-out test tiers ─────────────────────────────
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        tier_samples = {
            "unseen_mu": sample_operator_sobol(obox, N_TEST_PER_TIER, seed=TIER_SEEDS["unseen_mu"],
                                                exclude_strike_range=strike_holdout),
            "unseen_strike": sample_operator_gap(obox, N_TEST_PER_TIER, seed=TIER_SEEDS["unseen_strike"],
                                                  strike_range=strike_holdout),
            "unseen_combo": sample_operator_combo(obox, N_TEST_PER_TIER, seed=TIER_SEEDS["unseen_combo"]),
        }

    print("\nexp14: solving held-out test trajectories and evaluating both models...")
    results: dict[str, dict[str, dict[str, list[float]]]] = {}
    for tier, samples in tier_samples.items():
        test_trajs = []
        for mu, payoff in samples:
            result = generate_one_sample(mu, payoff, FIXED_MESH, TIME_GRID, mode="toeplitz")
            if result.ok:
                test_trajs.append((mu, payoff, result.traj))
        print(f"  {tier}: {len(test_trajs)}/{N_TEST_PER_TIER} reference solves succeeded")

        op_result = evaluate_model(operator_net, test_trajs, ops, stats)
        old_result = evaluate_model(old_net, test_trajs, ops, stats)
        results[tier] = {"operator": op_result, "parameter_map": old_result}

        for name, r in (("operator", op_result), ("parameter_map (old, K=100-only)", old_result)):
            print(f"    [{name}] mean rel_l2={np.mean(r['rel_l2']):.4e}  "
                  f"mean rel_energy={np.mean(r['rel_energy']):.4e}  "
                  f"mean eta_guar={np.mean(r['eta_guar']) if r['eta_guar'] else float('nan'):.4e}  "
                  f"mean effectivity={np.mean(r['effectivity']) if r['effectivity'] else float('nan'):.2f}  "
                  f"not_spd={r['n_not_spd']}/{r['n']}")

    # ── HDF5 ─────────────────────────────────────────────────────────────
    arrays = {}
    for tier, models in results.items():
        for model_name, r in models.items():
            key = f"{tier}_{model_name}"
            arrays[f"{key}_rel_l2"] = np.array(r["rel_l2"])
            arrays[f"{key}_rel_energy"] = np.array(r["rel_energy"])
            arrays[f"{key}_eta_guar"] = np.array(r["eta_guar"])
            arrays[f"{key}_effectivity"] = np.array(r["effectivity"])
    write_h5(
        RESULTS_DIR / "exp14_operator_generalization.h5", arrays,
        attrs={
            "n_train": len(train_trajs), "n_epochs": N_EPOCHS, "seed": SEED,
            "strike_min": strike_min, "strike_max": strike_max,
            "strike_holdout_lo": strike_holdout[0], "strike_holdout_hi": strike_holdout[1],
            "n_test_per_tier": N_TEST_PER_TIER, "operator_train_time_s": t_train,
        },
    )

    # ── Figure ───────────────────────────────────────────────────────────
    tiers = list(results.keys())
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5))
    metrics = [("rel_l2", "relative $L_2$ error"), ("rel_energy", "relative energy error"), ("eta_guar", r"$\eta_{guar}$")]
    for ax, (key, label) in zip(axes, metrics):
        x = np.arange(len(tiers))
        width = 0.35
        op_means = [np.mean(results[t]["operator"][key]) if results[t]["operator"][key] else np.nan for t in tiers]
        old_means = [np.mean(results[t]["parameter_map"][key]) if results[t]["parameter_map"][key] else np.nan for t in tiers]
        ax.bar(x - width / 2, op_means, width, label="operator (varying K)", color="C0")
        ax.bar(x + width / 2, old_means, width, label="parameter map (K=100 only)", color="C3")
        ax.set_xticks(x); ax.set_xticklabels(tiers, rotation=15, fontsize=8)
        ax.set_yscale("log")
        ax.set_ylabel(label)
        ax.legend(fontsize=7)
    fig.suptitle(f"exp14: operator vs. parameter-map generalization (n={N_TEST_PER_TIER}/tier)")
    fig.tight_layout()
    fig_path = FIGURES_DIR / "exp14_operator_generalization.png"
    fig.savefig(fig_path, dpi=150)
    print(f"\nwrote {fig_path}")

    # ── LaTeX table ──────────────────────────────────────────────────────
    header = ["tier", "model", "mean rel $L_2$", "mean rel energy", "mean $\\eta_{guar}$", "mean effectivity", "not-SPD"]
    rows = []
    for tier in tiers:
        for model_name, label in (("operator", "operator (varying K)"), ("parameter_map", "parameter map (K=100 only)")):
            r = results[tier][model_name]
            rows.append([
                tier, label, fmt(np.mean(r["rel_l2"])), fmt(np.mean(r["rel_energy"])),
                fmt(np.mean(r["eta_guar"])) if r["eta_guar"] else "n/a",
                f"{np.mean(r['effectivity']):.2f}" if r["effectivity"] else "n/a",
                f"{r['n_not_spd']}/{r['n']}",
            ])
    tex_path = TABLES_DIR / "exp14_operator_generalization.tex"
    write_latex_table(tex_path, header, rows)
    print(f"wrote {tex_path}")


if __name__ == "__main__":
    main()
