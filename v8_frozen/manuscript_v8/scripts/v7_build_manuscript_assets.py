def scaling():
    out = rd("M7_scaling", "scaling/outcomes.csv")
    tim = {r["key"]: r for r in rd("M7_scaling", "scaling/raw_timings.csv")}
    mem = rd("M7_scaling", "scaling/memory.csv")
    rd("M7_scaling", "scaling/not_applicable.csv")
    res = {}
    for N in (64, 128, 256, 512):
        for m in ("reference_trusted", "free_direct_lu", "free_cold_gmres"):
            rs = [r for r in out if int(r["N"]) == N and r["solver_method"] == m]
            byq = defaultdict(list)
            for r in rs:
                byq[r["query_id"]].append(r)
            ph = defaultdict(list)
            tq = []
            for q, qr in byq.items():
                tq.append(statistics.median(fl(r["total_time_s"]) for r in qr))
                P = [json.loads(tim[r["key"]]["phases_json"]) for r in qr]
                for k in ("setup_operator_cache", "setup_problem", "solve", "gate", "certify"):
                    ph[k].append(statistics.median(p.get(k, 0.0) for p in P))
            res[(N, m)] = dict(n_dof=int(rs[0]["n_dof"]), nq=len(byq), nrows=len(rs),
                               ver=sum(r["target_status"] == "verified" for r in rs), t=statistics.median(tq),
                               **{k: statistics.median(v) for k, v in ph.items()},
                               pcg=statistics.median(fl(r["pcg_iterations_total"]) for r in rs),
                               mem=statistics.median(fl(r["peak_traced_bytes"]) for r in mem
                                                     if int(r["N"]) == N and r["solver_method"] == m) / 2 ** 20)
    rows = []
    for (N, m), v in res.items():
        rows.append([str(N), str(v["n_dof"]), METHOD_LABEL[m].replace(" + certificate", ""), f"{v['ver']}/{v['nrows']}",
                     num(v["t"], 2), num(v["setup_operator_cache"], 2), num(v["solve"], 3), num(v["gate"], 3),
                     num(v["certify"], 2), f"{v['pcg']:.0f}", num(v["mem"], 1)])
    write_table("tab_scaling",
                "Solver and certificate cost under spatial refinement (cold mode, fixed 60 CN steps, single thread; "
                "\\texttt{Q\\_scale}: 30 queries at $N\\le256$, a predeclared 6 at $N=512$; 3 timed repetitions). "
                "Neural and POD models are $N=64$ artefacts with no transfer strategy and are not run at $N\\ne64$: "
                "this measures deterministic solve and certification costs, not neural or POD scaling. "
                "Times in seconds (median over queries of repetition medians); memory is the median peak traced allocation.",
                "tab:scaling", "rrlrrrrrrrr",
                ["$N$", "dof", "method", "verified", "total", "assembly", "solve", "gate", "certify", "PCG it.", "MB"],
                rows, resize=True)
    return res


