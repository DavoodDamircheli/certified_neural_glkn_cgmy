def rj(run: str, rel: str):
    p = R / RUNS[run] / rel
    raw = p.read_bytes()
    READ[f"{RUNS[run]}/{rel}"] = hashlib.sha256(raw).hexdigest()
    return json.loads(raw)


def rd(run: str, rel: str) -> list[dict]:
    p = R / RUNS[run] / rel
    READ[f"{RUNS[run]}/{rel}"] = hashlib.sha256(p.read_bytes()).hexdigest()
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def fl(x) -> float:
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def sci(x: float, d: int = 2) -> str:
    if x != x:
        return "--"
    if x == 0:
        return "$0$"
    e = int(math.floor(math.log10(abs(x))))
    if -2 <= e <= 2:
        return f"${x:.{max(d - e, 0)}f}$" if e < d else f"${x:.0f}$"
    m = x / 10 ** e
    return f"${m:.{d}f}\\times10^{{{e}}}$"


def num(x: float, d: int = 2) -> str:
    return "--" if x != x else f"${x:.{d}f}$"


def write_table(name: str, caption: str, label: str, cols: str, header: list[str], rows: list[list[str]],
                note: str = "", resize: bool = False) -> None:
    body = [r"\begin{table}[ht]", r"\centering\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}"]
    if resize:
        body.append(r"\resizebox{\textwidth}{!}{%")
    body += [f"\\begin{{tabular}}{{{cols}}}", r"\toprule", " & ".join(header) + r"\\", r"\midrule"]
    body += [" & ".join(r) + r"\\" for r in rows]
    body += [r"\bottomrule", r"\end{tabular}" + ("}" if resize else "")]
    if note:
        body.append(f"\\par\\smallskip\\parbox{{0.95\\linewidth}}{{\\footnotesize {note}}}")
    body.append(r"\end{table}")
    (TAB / f"{name}.tex").write_text(
        f"% GENERATED by scripts/v7_build_manuscript_assets.py from raw CSVs -- do not edit by hand\n"
        + "\n".join(body) + "\n")


