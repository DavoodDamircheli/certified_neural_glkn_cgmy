def t_refinement():
    rows = rd("M8_refinement", "refinement/prices.csv")
    cos = defaultdict(dict)
    for r in rd("M8_refinement", "cos/cos.csv"):
        cos[r["query_id"]][round(fl(r["spot"]), 9)] = fl(r["cos_price"])
    man = rj("M8_refinement", "manifest.json")
    P = {(r["query_id"], r["study"], int(r["N"]), int(r["n_steps"]), float(r["half_width"])): json.loads(r["prices"])
         for r in rows}
    qids = sorted({r["query_id"] for r in rows})
    out = []
    for study, lab in (("spatial", "space"), ("temporal", "time"), ("domain", "domain")):
        lv = [tuple(x) for x in man["levels"][study]]
        for i, (N, nst, L) in enumerate(lv):
            d, c = [], []
            for q in qids:
                v = P[(q, study, N, nst, float(L))]
                c.append(max(abs(a - b) for a, b in zip(v, [cos[q][s] for s in sorted(cos[q])])))
                if i + 1 < len(lv):
                    v2 = P[(q, study, *lv[i + 1][:2], float(lv[i + 1][2]))]
                    d.append(max(abs(a - b) for a, b in zip(v, v2)))
            out.append([lab, str(N), str(nst), num(float(L), 0), sci(statistics.median(d)) if d else "--",
                        sci(statistics.median(c))])
    write_table("tab_refinement",
                "Refinement of the production discrete price (first 8 \\texttt{Q\\_ref30} queries; spots $0.8K..1.2K$, "
                "maximum within query, then median over queries). Paired difference $=\\max_s|V_k-V_{k+1}|$ to the next "
                "level; COS gap is an independent continuum diagnostic. Space: $h=16/N$, 480 steps; time: $N=1024$; "
                "domain: $h=0.125$ fixed, half-width $L$.",
                "tab:refinement", "lrrrrr", ["study", "$N$", "steps", "$L$", "paired diff. (\\$)", "COS gap (\\$)"], out)


