def ratio_cell(prs, wl, mode, m, b):
    r = next((x for x in prs[mode] if x["workload"] == wl and x["method"] == m and x["baseline"] == b), None)
    if r is None or not r["n_common_qualifying"]:
        return "--"
    return f"{r['geomean_time_ratio']:.2f} [{r['geomean_ci_low']:.2f}, {r['geomean_ci_high']:.2f}]"


