def t_riesz():
    rows = rd("M6_riesz", "riesz/riesz_bracket_validation.csv")
    alpha = rd("M6_riesz", "riesz/alpha_check.csv")
    out = []
    names = {"reference": "Stored reference", "raw_neural": "Raw DeepONet candidate", "pod_r16": "POD $r=16$",
             "pod_r32": "POD $r=32$", "corrected": "Corrected trajectory", "manufactured": "Manufactured SPD"}
    for s in ("reference", "raw_neural", "pod_r16", "pod_r32", "corrected", "manufactured"):
        rs = [r for r in rows if r["residual_source"] == s]
        rn = [fl(r["residual_norm"]) for r in rs]
        c = Counter(r["comparison_status"] for r in rs)
        side = Counter(r["unresolved_side"] for r in rs if r["comparison_status"] == "numerically_unresolved")
        out.append([names[s], f"{sci(min(rn), 1)}--{sci(max(rn), 1)}", str(len(rs)), str(c["pass"]),
                    f"{c['numerically_unresolved']} ({side['lower+upper']}/{side['lower']})", str(c["violation"])])
    tot = Counter(r["comparison_status"] for r in rows)
    out.append([r"\textbf{All}", "", str(len(rows)), str(tot["pass"]), str(tot["numerically_unresolved"]), str(tot["violation"])])
    write_table("tab_riesz_brackets",
                "Riesz-bracket validation against a 40-digit reference on the same assembled $S_I$ "
                "(24 declared audit queries, steps $n\\in\\{0,30,59\\}$, PCG budgets $\\{0,\\dots,200\\}$, four preconditioners; "
                "manufactured: $n=62$, $\\mathrm{cond}\\le10^8$). Unresolved = a margin within the comparison uncertainty "
                "$8n\\varepsilon_{\\rm mach}\\mathrm{cond}_2(S)q$ (both sides/lower only); unresolved rows are not confirmed passes.",
                "tab:riesz", "lrrrrr",
                ["Residual source", "$\\|r\\|_2$ range", "rows", "resolved pass", "unresolved", "violations"], out,
                note=f"$\\alpha\\le\\lambda_{{\\min}}(S_I)$ against the 40-digit eigenvalue of the same matrix held on "
                     f"{sum(r['hypothesis_alpha_le_lambda_min_holds'] == 'True' for r in alpha)}/{len(alpha)} queries "
                     f"(finite-sample evidence). The reference validates the bracket implementation, not assembly accuracy "
                     f"or an outward-rounded enclosure.")


