def C(id, section, text, json_, path=None, expr=None, value=None, tol="round", rel="eq", note="", transform="",
      file=None, regex=None, group=None, agg=None, module=None, kind=None, attention=""):
    c = dict(id=id, section=section, text=text, json=json_)
    for k, v in (("file", file), ("regex", regex), ("group", group), ("agg", agg), ("module", module), ("kind", kind),
                 ("attention", attention)):
        if v:
            c[k] = v
    if transform:
        c["transform"] = transform
    if path is not None:
        c["path"] = path
    if expr is not None:
        c["expr"] = expr
    if value is not None:
        c["value"] = value
    c["tol"] = tol
    if rel != "eq":
        c["rel"] = rel
    if note:
        c["note"] = note
    CLAIMS.append(c)


